#!/usr/bin/env python3
"""Render LaTeX Tables A/B/C/E from per-run eval JSONs.

Expects directory layout:
  results/eval/<scene>_run<N>_<sha>/
    benchmark.json       # from benchmark_stcm_graph.py
    per_label.json       # from per_label_metrics.py
    nav.json             # from nav_sim.py
    grounding.json       # from grounding.py
  paper/tables/dataset_card.json  # from dataset_card.py

Aggregates 3 runs per scene as mean ± std and writes:
  paper/tables/A.tex  -- dataset card
  paper/tables/B.tex  -- nav success rate per scene
  paper/tables/C.tex  -- semantic F1 / mIoU per scene
  paper/tables/E.tex  -- grounding accuracy per subset

Usage:
  python3 scripts/eval/render_tables.py \
      --eval-root results/eval \
      --scenes meeting livinglab \
      --dataset-card paper/tables/dataset_card.json \
      --output-dir paper/tables
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
from typing import Any


def _mean_std(values: list[float]) -> tuple[float | None, float]:
    vals = [v for v in values if v is not None and isinstance(v, (int, float)) and math.isfinite(v)]
    if not vals:
        return None, 0.0
    m = sum(vals) / len(vals)
    if len(vals) < 2:
        return m, 0.0
    var = sum((v - m) ** 2 for v in vals) / (len(vals) - 1)
    return m, math.sqrt(var)


def _fmt(mean: float | None, std: float, scale: float = 1.0, digits: int = 1) -> str:
    if mean is None:
        return "--"
    return f"{mean*scale:.{digits}f} $\\pm$ {std*scale:.{digits}f}"


def _load_runs(eval_root: Path, scene: str) -> list[dict[str, Any]]:
    runs: list[dict[str, Any]] = []
    for d in sorted(eval_root.glob(f"{scene}_run*")):
        if not d.is_dir():
            continue
        rec: dict[str, Any] = {"dir": d}
        for key, fname in [("benchmark", "benchmark.json"),
                           ("per_label", "per_label.json"),
                           ("nav", "nav.json"),
                           ("grounding", "grounding.json")]:
            p = d / fname
            if p.exists():
                try:
                    rec[key] = json.loads(p.read_text())
                except Exception:
                    rec[key] = None
        runs.append(rec)
    return runs


def _render_A(card_path: Path) -> str:
    cards = json.loads(card_path.read_text()).get("cards", [])
    rows = []
    for c in cards:
        scene = c.get("scene", "")
        dur = c.get("duration_s")
        dur_s = f"{dur:.0f}" if isinstance(dur, (int, float)) else "--"
        gt = c.get("gt_instance_count") or 0
        vocab = len(c.get("label_vocabulary") or [])
        storage = c.get("storage_id") or "--"
        rows.append(f"  {scene} & {storage} & {dur_s} & {vocab} & {gt} \\\\")
    body = "\n".join(rows)
    return (
        "% Auto-generated by scripts/eval/render_tables.py\n"
        "\\begin{tabular}{lcccc}\n"
        "  \\toprule\n"
        "  Scene & Storage & Duration (s) & Vocabulary size & GT instances \\\\\n"
        "  \\midrule\n"
        f"{body}\n"
        "  \\bottomrule\n"
        "\\end{tabular}\n"
    )


def _render_B(scenes: list[str], runs_by_scene: dict[str, list[dict[str, Any]]]) -> str:
    rows = []
    for scene in scenes:
        runs = runs_by_scene.get(scene, [])
        rates = [r["nav"]["success_rate"] for r in runs if r.get("nav") and r["nav"].get("success_rate") is not None]
        ratios = [r["nav"]["mean_path_ratio"] for r in runs if r.get("nav") and r["nav"].get("mean_path_ratio") is not None]
        n_trials = runs[0]["nav"].get("n_trials") if runs and runs[0].get("nav") else "--"
        rate_m, rate_s = _mean_std(rates)
        ratio_m, ratio_s = _mean_std(ratios)
        rows.append(
            f"  {scene} & {len(runs)} & {n_trials} & "
            f"{_fmt(rate_m, rate_s, scale=100, digits=1)}\\% & "
            f"{_fmt(ratio_m, ratio_s, digits=2)} \\\\"
        )
    body = "\n".join(rows)
    return (
        "% Auto-generated by scripts/eval/render_tables.py\n"
        "\\begin{tabular}{lcccc}\n"
        "  \\toprule\n"
        "  Scene & Runs & Trials/run & Success rate & Path ratio \\\\\n"
        "  \\midrule\n"
        f"{body}\n"
        "  \\bottomrule\n"
        "\\end{tabular}\n"
        "% Caption note: graph-feasibility navigation success — control loop not closed;\n"
        "% measures whether the built map supports planning to labelled goals.\n"
    )


def _render_C(scenes: list[str], runs_by_scene: dict[str, list[dict[str, Any]]]) -> str:
    rows = []
    for scene in scenes:
        runs = runs_by_scene.get(scene, [])
        macro_f1 = [r["per_label"]["macro_f1"] for r in runs if r.get("per_label")]
        micro_f1 = [r["per_label"]["micro_f1"] for r in runs if r.get("per_label")]
        macro_iou = [r["per_label"]["macro_iou"] for r in runs if r.get("per_label")]
        micro_iou = [r["per_label"]["micro_iou"] for r in runs if r.get("per_label")]
        bench_f1 = [r["benchmark"]["summary"]["overall"]["f1"]
                    for r in runs if r.get("benchmark") and r["benchmark"].get("summary", {}).get("overall")]
        rows.append(
            f"  {scene} & {len(runs)} & "
            f"{_fmt(*_mean_std(macro_f1), digits=3)} & "
            f"{_fmt(*_mean_std(micro_f1), digits=3)} & "
            f"{_fmt(*_mean_std(macro_iou), digits=3)} & "
            f"{_fmt(*_mean_std(micro_iou), digits=3)} \\\\"
        )
    body = "\n".join(rows)
    return (
        "% Auto-generated by scripts/eval/render_tables.py\n"
        "\\begin{tabular}{lccccc}\n"
        "  \\toprule\n"
        "  Scene & Runs & Macro-F1 & Micro-F1 & Macro-mIoU & Micro-mIoU \\\\\n"
        "  \\midrule\n"
        f"{body}\n"
        "  \\bottomrule\n"
        "\\end{tabular}\n"
    )


def _render_E(scenes: list[str], runs_by_scene: dict[str, list[dict[str, Any]]]) -> str:
    rows = []
    subsets = ["simple", "disambiguation", "compositional"]
    for scene in scenes:
        runs = runs_by_scene.get(scene, [])
        cells: list[str] = [scene, str(len(runs))]
        for subset in subsets:
            top1 = [r["grounding"]["by_subset"].get(subset, {}).get("top1_acc")
                    for r in runs if r.get("grounding")]
            top2 = [r["grounding"]["by_subset"].get(subset, {}).get("top2_acc")
                    for r in runs if r.get("grounding")]
            cells.append(_fmt(*_mean_std(top1), scale=100, digits=1) + "\\%")
            cells.append(_fmt(*_mean_std(top2), scale=100, digits=1) + "\\%")
        ov_top1 = [r["grounding"]["overall"]["top1_acc"] for r in runs if r.get("grounding")]
        ov_top2 = [r["grounding"]["overall"]["top2_acc"] for r in runs if r.get("grounding")]
        cells.append(_fmt(*_mean_std(ov_top1), scale=100, digits=1) + "\\%")
        cells.append(_fmt(*_mean_std(ov_top2), scale=100, digits=1) + "\\%")
        rows.append("  " + " & ".join(cells) + " \\\\")
    body = "\n".join(rows)
    header = (
        "  Scene & Runs & "
        "Simple top-1 & Simple top-2 & "
        "Disambig top-1 & Disambig top-2 & "
        "Compose top-1 & Compose top-2 & "
        "Overall top-1 & Overall top-2 \\\\"
    )
    return (
        "% Auto-generated by scripts/eval/render_tables.py\n"
        "\\begin{tabular}{lccccccccc}\n"
        "  \\toprule\n"
        f"{header}\n"
        "  \\midrule\n"
        f"{body}\n"
        "  \\bottomrule\n"
        "\\end{tabular}\n"
    )


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--eval-root", default="results/eval", type=Path)
    ap.add_argument("--scenes", nargs="+", default=["meeting", "livinglab"])
    ap.add_argument("--dataset-card", default="paper/tables/dataset_card.json", type=Path)
    ap.add_argument("--output-dir", default="paper/tables", type=Path)
    args = ap.parse_args()

    args.output_dir.mkdir(parents=True, exist_ok=True)

    runs_by_scene = {scene: _load_runs(args.eval_root, scene) for scene in args.scenes}

    if args.dataset_card.exists():
        (args.output_dir / "A.tex").write_text(_render_A(args.dataset_card))
        print(f"wrote {args.output_dir / 'A.tex'}")
    else:
        print(f"skip A.tex: {args.dataset_card} not found")

    (args.output_dir / "B.tex").write_text(_render_B(args.scenes, runs_by_scene))
    print(f"wrote {args.output_dir / 'B.tex'}")
    (args.output_dir / "C.tex").write_text(_render_C(args.scenes, runs_by_scene))
    print(f"wrote {args.output_dir / 'C.tex'}")
    (args.output_dir / "E.tex").write_text(_render_E(args.scenes, runs_by_scene))
    print(f"wrote {args.output_dir / 'E.tex'}")


if __name__ == "__main__":
    main()
