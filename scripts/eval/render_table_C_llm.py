#!/usr/bin/env python3
"""Render LaTeX Table C for AE-3 LLM ablation from McNemar JSONs.

Reads:
  results/grounding/<scene>_grounding_spatial.json   (no-LLM)
  results/grounding/<scene>_grounding_intent.json    (intent-lexicon)
  results/grounding_llm/<scene>_grounding.json       (LLM)
  paper/tables/C_<pair>_<partition>_<scene>.json     (paired stats)

Writes:
  paper/tables/C_llm_ablation.tex
  paper/tables/C_llm_ablation_failure_breakdown.tex (small auxiliary)

Usage:
  python3 scripts/eval/render_table_C_llm.py --scene meeting

The reviewer-facing framing is split: a primary block over the explicit
spatial commands (10 simple + 10 disambiguation + 10 compositional) and a
secondary block over the functional / intent commands. The pooled overall
row is marked exploratory.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


_TEX_HEADER = r"""% Auto-generated by scripts/eval/render_table_C_llm.py
% Reviewer comment AE-3 (JACIII Jc26-0002): LLM ablation with statistical analysis.
\begin{tabular}{llcccccc}
  \toprule
  Partition & Arm & Top-1 & 95\% CI & $\Delta$ vs.\ no-LLM & 95\% CI ($\Delta$) & McNemar $p$ & $b$/$c$ \\
  \midrule
"""

_TEX_FOOTER = r"""  \bottomrule
\end{tabular}
"""


def _fmt(x: float) -> str:
    return f"{x:.3f}"


def _fmt_ci(ci: list[float]) -> str:
    return f"[{ci[0]:.3f}, {ci[1]:.3f}]"


def _row(partition: str, arm: str, acc: float, acc_ci: list[float],
         delta: float | None, delta_ci: list[float] | None,
         p: float | None, b: int | None, c: int | None) -> str:
    if delta is None:
        return (f"  {partition} & {arm} & {_fmt(acc)} & {_fmt_ci(acc_ci)} "
                f"& --- & --- & --- & --- \\\\\n")
    return (f"  {partition} & {arm} & {_fmt(acc)} & {_fmt_ci(acc_ci)} "
            f"& {delta:+.3f} & {_fmt_ci(delta_ci)} "
            f"& {p:.4f} & {b}/{c} \\\\\n")


def _load_arm(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text())


def _arm_metrics(report: dict[str, Any], subsets: list[str] | None) -> tuple[float, float, float, int, int]:
    """Return (top1_acc, n, n_eligible, n_correct, n_eligible_correct) over the partition."""
    rows = report.get("trials", [])
    if subsets is not None:
        wanted = set(subsets)
        rows = [r for r in rows if r.get("subset") in wanted]
    n = len(rows)
    n_correct = sum(1 for r in rows if r.get("top1"))
    n_elig = sum(1 for r in rows if r.get("eligible_grounding_given_perception"))
    n_elig_correct = sum(1 for r in rows
                         if r.get("eligible_grounding_given_perception") and r.get("top1"))
    acc = n_correct / n if n else 0.0
    return acc, n, n_elig, n_correct, n_elig_correct


def _wilson_ci(k: int, n: int, z: float = 1.96) -> list[float]:
    if n == 0:
        return [0.0, 0.0]
    import math
    p = k / n
    denom = 1 + z * z / n
    center = (p + z * z / (2 * n)) / denom
    half = (z * math.sqrt((p * (1 - p) + z * z / (4 * n)) / n)) / denom
    return [max(0.0, center - half), min(1.0, center + half)]


def _render_block(partition_name: str,
                  subsets: list[str] | None,
                  noLLM: dict[str, Any],
                  intent: dict[str, Any],
                  llm: dict[str, Any],
                  pair_llm_vs_noLLM: dict[str, Any] | None,
                  pair_intent_vs_noLLM: dict[str, Any] | None) -> str:
    no_acc, n, _, no_k, _ = _arm_metrics(noLLM, subsets)
    in_acc, _, _, in_k, _ = _arm_metrics(intent, subsets)
    ll_acc, _, _, ll_k, _ = _arm_metrics(llm, subsets)
    out = ""
    out += _row(partition_name, "no-LLM (template)", no_acc, _wilson_ci(no_k, n),
                None, None, None, None, None)
    if pair_intent_vs_noLLM:
        ov = pair_intent_vs_noLLM["overall"]
        out += _row(partition_name, "+intent-lexicon", in_acc,
                    _wilson_ci(in_k, n),
                    ov["delta_acc_llm_minus_baseline"],
                    ov["delta_acc_ci95"],
                    ov["p_value_exact"],
                    ov["discordant_b_llm_only"],
                    ov["discordant_c_baseline_only"])
    else:
        out += _row(partition_name, "+intent-lexicon", in_acc,
                    _wilson_ci(in_k, n), None, None, None, None, None)
    if pair_llm_vs_noLLM:
        ov = pair_llm_vs_noLLM["overall"]
        out += _row(partition_name, "+LLM (Sonnet 4.6, T=0)", ll_acc,
                    _wilson_ci(ll_k, n),
                    ov["delta_acc_llm_minus_baseline"],
                    ov["delta_acc_ci95"],
                    ov["p_value_exact"],
                    ov["discordant_b_llm_only"],
                    ov["discordant_c_baseline_only"])
    else:
        out += _row(partition_name, "+LLM (Sonnet 4.6, T=0)", ll_acc,
                    _wilson_ci(ll_k, n), None, None, None, None, None)
    return out


def _render_failure_table(reports: dict[str, dict[str, Any]]) -> str:
    keys = ["none", "perception_missing", "alias_label_error",
            "relation_error", "ranker_error", "llm_invalid_id"]
    out = "% Auto-generated failure breakdown\n"
    out += r"\begin{tabular}{l" + "r" * len(keys) + "}" + "\n"
    out += r"  \toprule" + "\n"
    out += "  Arm & " + " & ".join(k.replace("_", "\\_") for k in keys) + r" \\" + "\n"
    out += r"  \midrule" + "\n"
    for arm_name, rep in reports.items():
        counts = rep["overall"].get("failure_counts", {})
        cells = [str(counts.get(k, 0)) for k in keys]
        out += f"  {arm_name} & " + " & ".join(cells) + r" \\" + "\n"
    out += r"  \bottomrule" + "\n"
    out += r"\end{tabular}" + "\n"
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--scene", default="meeting")
    ap.add_argument("--results-dir", default=Path("."), type=Path)
    ap.add_argument("--paper-tables", default=Path("paper/tables"), type=Path)
    ap.add_argument("--output", default=Path("paper/tables/C_llm_ablation.tex"),
                    type=Path)
    args = ap.parse_args()

    res = args.results_dir
    pt = args.paper_tables
    s = args.scene

    noLLM = _load_arm(res / f"results/grounding/{s}_grounding_spatial.json")
    intent = _load_arm(res / f"results/grounding/{s}_grounding_intent.json")
    llm = _load_arm(res / f"results/grounding_llm/{s}_grounding.json")

    pair = lambda kind, part: _load_arm(pt / f"C_{kind}_{part}_{s}.json")

    # spatial 30: simple+disambig+compose
    sp_subsets = ["simple", "disambiguation", "compositional"]
    sp_llm_vs_no = pair("llm_vs_noLLM", "spatial30")
    sp_int_vs_no = None  # not run; intent identical to no-LLM on spatial subsets
    # functional 15
    fu_llm_vs_no = pair("llm_vs_noLLM", "functional15")
    fu_int_vs_no = pair("intent_vs_noLLM", "functional15")
    # overall 45 (exploratory)
    ov_llm_vs_no = pair("llm_vs_noLLM", "overall45")
    # eligible-only (n=39)
    el_llm_vs_no = _load_arm(pt / f"C_llm_vs_noLLM_eligible_{s}.json")
    el_int_vs_no = _load_arm(pt / f"C_intent_vs_noLLM_eligible_{s}.json")

    out = _TEX_HEADER
    out += _render_block("Spatial (n=30)", sp_subsets, noLLM, intent, llm,
                         sp_llm_vs_no, sp_int_vs_no)
    out += r"  \midrule" + "\n"
    out += _render_block("Functional (n=15)", ["functional"], noLLM, intent, llm,
                         fu_llm_vs_no, fu_int_vs_no)
    out += r"  \midrule" + "\n"
    out += _render_block("Pooled (n=45, exploratory)", None, noLLM, intent, llm,
                         ov_llm_vs_no, None)
    out += r"  \midrule" + "\n"
    out += _render_block("Eligible / grounding-given-perception (n=39)",
                         None, noLLM, intent, llm,
                         el_llm_vs_no, el_int_vs_no)
    # Eligible block uses all subsets but restricts to eligible commands; the
    # accuracy numbers above will be over the full n=45 partition because
    # _arm_metrics doesn't filter eligibility. Override by rewriting the
    # block from explicit conditional fields:
    out_lines = out.splitlines(keepends=True)
    # Replace the last 3 rows (one per arm) with eligible-conditional accuracies.
    elig_block = ""
    for arm_name, rep, pair_stats in [
        ("no-LLM (template)", noLLM, None),
        ("+intent-lexicon", intent, el_int_vs_no),
        ("+LLM (Sonnet 4.6, T=0)", llm, el_llm_vs_no),
    ]:
        ov = rep["overall"]
        n_e = ov["n_eligible"]
        k_e = ov["top1_eligible"]
        acc = ov["top1_acc_given_perception"]
        ci = _wilson_ci(k_e, n_e)
        if pair_stats is None:
            elig_block += _row("Eligible (n=39)", arm_name, acc, ci,
                               None, None, None, None, None)
        else:
            o = pair_stats["overall"]
            elig_block += _row("Eligible (n=39)", arm_name, acc, ci,
                               o["delta_acc_llm_minus_baseline"],
                               o["delta_acc_ci95"],
                               o["p_value_exact"],
                               o["discordant_b_llm_only"],
                               o["discordant_c_baseline_only"])
    # Drop the last block we appended (3 rows after the last \midrule), then
    # replace with eligible-corrected rows.
    text = "".join(out_lines)
    midrules = [i for i, ln in enumerate(out_lines) if ln.strip() == r"\midrule"]
    if midrules:
        last = midrules[-1]
        out = "".join(out_lines[: last + 1]) + elig_block
    out += _TEX_FOOTER

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(out)
    print(f"wrote {args.output}")

    fail_path = args.output.with_name(args.output.stem + "_failure_breakdown.tex")
    fail_path.write_text(_render_failure_table({
        "no-LLM (template)": noLLM,
        "+intent-lexicon": intent,
        "+LLM (Sonnet 4.6, T=0)": llm,
    }))
    print(f"wrote {fail_path}")


if __name__ == "__main__":
    main()
